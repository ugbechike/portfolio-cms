import { writeFile } from "node:fs/promises";
import {
  kindSchema,
  projectSchema,
  experienceSchema,
  noteSchema,
  profileSchema,
} from "@portfolio/contracts";
const rows: string[] = [];
for (const kind of kindSchema.options) {
  rows.push(`| GET | /api/v1/${kind} | Public published snapshots |`);
  if (kind === "projects" || kind === "notes")
    rows.push(
      `| GET | /api/v1/${kind}/:slug | Published snapshot by published slug |`,
    );
  for (const [method, path, meaning] of [
    ["GET", "", "List drafts and publication status"],
    ["POST", "", "Create draft"],
    ["GET", "/:id", "Read editable record"],
    ["PATCH", "/:id", "Replace draft"],
    ["DELETE", "/:id", "Delete and audit"],
    ["POST", "/:id/publish", "Publish saved draft"],
    ["POST", "/:id/unpublish", "Withdraw snapshot"],
    ["POST", "/:id/archive", "Archive and withdraw"],
    ["GET", "/:id/revisions", "Latest 100 revisions"],
    ["POST", "/:id/restore", "Restore revision into draft"],
  ])
    rows.push(`| ${method} | /api/v1/admin/${kind}${path} | ${meaning} |`);
}
const content = `# API reference

Generated by \`pnpm docs:api\`. Shared schemas in \`packages/contracts\` are authoritative.

Base: \`/api/v1\`. Administrative routes require \`Authorization: Bearer <Supabase access token>\` from the allowlisted user. Public routes require no token and never return the draft field. All admin responses and public content/media routes use Cache-Control: no-store.

## Response envelopes

Success: \`{ "data": ... }\`. Lists add \`"meta": { "page": 1, "limit": 20, "total": 0 }\`. Errors: \`{ "error": { "code": "...", "message": "...", "details": ... }, "requestId": "..." }\`; details and requestId are optional. Statuses: 400 validation, 401 unauthenticated, 403 forbidden, 404 absent, 409 slug/version/media conflict, 422 publication validation, 429 rate limit, 500 internal, 502 storage upstream failure.

## Content endpoints

| Method | Path | Behavior |
| --- | --- | --- |
${rows.join("\n")}

Create body is the full shared content object with its discriminator \`kind\`. Defaults are supplied for optional fields. PATCH takes \`{ "content": <full content object>, "expectedVersion": 1 }\`. It replaces the draft rather than performing a recursive merge. Publish, unpublish, archive, and DELETE bodies take \`{ "expectedVersion": 1 }\`. Restore adds \`revisionId\`. Versions increment on every successful mutation. Reload on VERSION_CONFLICT; never blindly retry with a guessed version.

List filters: \`page\` (1+), \`limit\` (1–100, default 20), \`q\` (title substring), admin \`status\` (draft/published/archived), and \`projectType\` (client/personal). Order: featured first, sortOrder ascending, most recently updated, UUID. Public ordering and search use the published payload. Public profile returns one object or null instead of an array. Other public collections return arrays. The profile slug is fixed and unique.

## Other endpoints

| Method | Path | Behavior |
| --- | --- | --- |
| GET | /health | Database connectivity; status ok |
| GET | /api/v1/admin/session | Authenticated admin ID |
| GET | /api/v1/admin/dashboard | Counts and 12 latest revision events |
| GET | /api/v1/admin/media | Latest 100 media records |
| POST | /api/v1/admin/media | Multipart: alt text field then one file; PNG/JPEG/WebP, max 10 MB |
| GET | /api/v1/admin/media/:id/url | Authenticated preview URL, expires in 60 seconds |
| DELETE | /api/v1/admin/media/:id | Delete only if no draft/published references |
| GET | /api/v1/media/:id | Redirect to signed URL only when referenced by a published snapshot |

Upload form fields must put \`alt\` before \`file\`. The API checks claimed MIME against file magic bytes and uses UUID paths. SVG is not accepted. Existing signed URLs remain valid for up to 60 seconds after withdrawal. Media/revision lists are intentionally bounded; content collections are paginated.

## Content field index

${Object.entries({
  projects: projectSchema,
  experiences: experienceSchema,
  notes: noteSchema,
  profile: profileSchema,
})
  .map(
    ([kind, schema]) =>
      `- **${kind}**: ${Object.keys(schema.shape)
        .map((k) => "\`" + k + "\`")
        .join(", ")}`,
  )
  .join("\n")}

Case-study section types: text, bullets, decision, challenge, metrics, image, code, diagram, links. Image sections reference a media UUID; diagram source is stored as text. Markdown/code are never executed by the CMS.

## Example sequence

1. POST an authenticated project draft with kind, title, slug and summary.
2. GET the public collection: the draft is absent.
3. POST /admin/projects/:id/publish with expectedVersion from creation.
4. GET /projects/:slug: the saved snapshot is visible.
5. PATCH a new draft using the returned version: the public snapshot remains unchanged until the next publish.
`;
await writeFile(new URL("../docs/API.md", import.meta.url), content);
